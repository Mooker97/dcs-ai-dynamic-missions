"""Run an Arma 3 mission unattended on a local dedicated server; parse the .rpt into a JSON report.

Usage:
    uv run python tools/arma_harness/run_mission.py arma/missions/dms_the_hill.Altis --minutes 15
        [--seed N] [--param KEY=VALUE ...] [--no-test-mode] [--wall-timeout SEC] [--port 2402]
        [--difficulty Regular] [--report out.json] [--keep-mission] [--dry-run]

How it works (details: docs/arma/TESTING.md):
  * Copies the mission folder to <Arma 3>/MPMissions/dms_<name>.<world> (the only thing written into
    the game install; removed again afterwards unless --keep-mission). Nothing else in the install
    is touched.
  * Writes server.cfg / basic.cfg into an isolated profile dir (default
    %LOCALAPPDATA%/dms/arma_test). server.cfg: LAN only, no password, BattlEye off,
    verifySignatures 0, persistent = 1 and one class Missions entry with the mission params
    (DMS_testMode = 1, DMS_seed, ...). With -autoInit the mission starts with no player connected.
  * Launches arma3server_x64.exe -config -cfg -profiles -name=dms -autoInit -port, tails the newest
    .rpt in the profile dir and stops on "[DMS.TEST] DONE" (or a SUMMARY / OUTCOME line), on
    --minutes of mission time + slack, or on the wall timeout. Then it kills the server it started.
  * Parses script errors (Error in expression / Error position / Error ... / File ..., line N),
    [DMS] lines, [DMS.TEST] PASS|FAIL lines and the [DMS.OUTCOME] line.

Exit codes: 0 = pass (summary reached, no FAIL, no script errors); 1 = ran with failures/errors;
2 = infra problem (server not found / already running / mission never started).
"""

