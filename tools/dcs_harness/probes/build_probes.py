"""Generate the DCS-unknowns probe missions (K1-K10) as small .miz files.

Each mission is generated from scratch with pydcs through ``dms_gen``'s MissionBuilder
(ADR 0001: generate, never load/save a user mission). It holds one blue AI vehicle ("Probe
Anchor") near Vaziani on Caucasus, any extra groups the probe needs, and one MISSION START
trigger with a DO SCRIPT FILE that runs ``lua/common.lua`` + the probe script (plus any runtime
module it needs, e.g. ``lua/src/dms/rng.lua`` for K5) concatenated into one file.

Usage:
    uv run python tools/dcs_harness/probes/build_probes.py [k1 k2 ...] [--out dist/probes]

Prints, per probe, the miz path and the run_mission.py command line (README.md has the details).
"""

# mypy: disallow-untyped-calls=False

from __future__ import annotations

import argparse
import datetime as dt
import importlib.util
import sys
import tempfile
from pathlib import Path
from types import ModuleType

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
LUA_DIR = HERE / "lua"
DEFAULT_OUT = REPO / "dist" / "probes"
HARNESS = "tools/dcs_harness/run_mission.py"
PARSER = "tools/dcs_harness/probes/parse_probes.py"

THEATER = "Caucasus"
ANCHOR_AIRPORT = "Vaziani"
ANCHOR_OFFSET = (-4000.0, 3000.0)  # m from the airport (x north, y east): open steppe
K1_GROUPS = (
    "K1 one_point",
    "K1 two_no_current",
    "K1 two_current_first",
    "K1 two_current_first_road",
    "K1 control",
)


def _load_parser() -> ModuleType:
    name = "dms_probe_parse_probes"
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, HERE / "parse_probes.py")
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


pp = _load_parser()


def probe_script(pid: str) -> str:
    """The single Lua file a probe mission runs: common helpers, extra modules, the probe."""
    info = pp.PROBES[pid]
    parts = [f"-- DMS probe {pid} ({info.title}). Generated by build_probes.py; Lua 5.1.\n"]
    files = [LUA_DIR / "common.lua", *(REPO / x for x in info.extra_lua), LUA_DIR / info.script]
    for f in files:
        rel = f.relative_to(REPO).as_posix()
        parts.append(f"-- ==== {rel} ====\n" + f.read_text(encoding="utf-8").rstrip() + "\n")
    return "\n".join(parts)


def harness_command(pid: str, miz: Path | str) -> list[str]:
    """run_mission.py argv for one run of this probe."""
    info = pp.PROBES[pid]
    cmd = ["uv", "run", "python", HARNESS, str(miz), "--minutes", f"{info.minutes:g}"]
    if info.accel > 1:
        cmd += ["--accel", str(info.accel)]
    cmd += ["--report", f"probe_{pid}_report.json"]
    if info.inject:
        cmd += ["--inject", info.inject]
    return cmd


def build_probe(pid: str, out_dir: Path) -> Path:
    from dms_gen.builder.mission import MissionBuilder  # type: ignore[import-untyped,unused-ignore]

    info = pp.PROBES[pid]
    b = MissionBuilder(THEATER, seed=1)
    b.set_datetime(dt.datetime(2026, 6, 1, 10, 0, 0))
    b.set_weather("clear")
    b.set_briefing(
        f"DMS probe {pid}: {info.title}",
        f"{info.question}\nHeadless measurement mission; logs [DMS.PROBE] lines to dcs.log.",
    )
    ap = b.terrain.airports[ANCHOR_AIRPORT].position
    ax, ay = ap.x + ANCHOR_OFFSET[0], ap.y + ANCHOR_OFFSET[1]
    b.add_ground_group("blue", "USA", "Probe Anchor", [("Hummer", 0, 0, 0)], (ax, ay))
    if pid == "k1":
        # identical BTR-80s 300 m apart (east-west) 1.5 km south of the anchor; routes go north
        for i, name in enumerate(K1_GROUPS):
            b.add_ground_group(
                "blue", "USA", name, [("BTR-80", 0, 0, 0)], (ax - 1500, ay + (i - 2) * 300)
            )
    with tempfile.TemporaryDirectory() as tmp:
        script = Path(tmp) / f"dms_probe_{pid}.lua"
        script.write_text(probe_script(pid), encoding="utf-8")
        b.embed_lua_files([script])
        out = Path(b.save(out_dir / info.miz_name))
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("probes", nargs="*", help=f"probe ids (default all: {', '.join(pp.PROBES)})")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output folder")
    a = ap.parse_args(argv)
    unknown = [p for p in a.probes if p not in pp.PROBES]
    if unknown:
        ap.error(f"unknown probe(s): {', '.join(unknown)}")
    wanted = a.probes or list(pp.PROBES)
    for pid in wanted:
        miz = build_probe(pid, a.out)
        info = pp.PROBES[pid]
        print(f"{pid}: {miz}")
        runs = f" (x{info.runs} runs)" if info.runs > 1 else ""
        print("    run" + runs + ": " + " ".join(_q(x) for x in harness_command(pid, miz)))
    print(f"parse: uv run python {PARSER} <write dir>/Logs/dcs.log [--probe kN]")
    return 0


def _q(s: str) -> str:
    return f'"{s}"' if (" " in s or "'" in s) else s


if __name__ == "__main__":
    sys.exit(main())
