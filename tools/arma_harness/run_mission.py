def cfg_value(v: object) -> str:
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, int | float):
        return str(v)
    s = str(v)
    if re.fullmatch(r"-?\d+(\.\d+)?", s):
        return s
    return '"' + s.replace('"', '""') + '"'


def server_cfg(template: str, params: dict[str, object], difficulty: str) -> str:
    plines = "\n".join(f"\t\t\t{k} = {cfg_value(v)};" for k, v in params.items())
