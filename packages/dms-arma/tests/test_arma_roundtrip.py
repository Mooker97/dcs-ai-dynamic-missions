"""Spec reconstructed from The Hill emits a fn_config.sqf semantically equal to the live one.

Known, intentional differences (values are identical; see docs/arma/BACKEND.md):
- comments and layout are regenerated, not preserved;
- integral numbers authored as floats would be written without a decimal point (none today).
"""

from __future__ import annotations

from arma_paths import EXAMPLE, HILL, ROOT
from dms_arma import (
    CONFIG_KEYS,
    config_diff,
    config_values,
    emit_config,
    load_spec,
    parse_config,
    spec_from_config,
)
from dms_arma.config import config_sections


def test_hill_round_trip_is_semantically_equal(hill_text: str) -> None:
    original = parse_config(hill_text)
    spec = spec_from_config(original)
    emitted = emit_config(spec)
    regenerated = parse_config(emitted)
    assert config_diff(original, regenerated) == []
    assert list(regenerated) == list(original), "key order should match the hand-written file"


def test_emit_is_deterministic(hill_text: str) -> None:
    spec = spec_from_config(parse_config(hill_text))
    assert emit_config(spec) == emit_config(spec.model_copy(deep=True))
    again = spec_from_config(parse_config(emit_config(spec)))
    assert again == spec
    assert emit_config(again) == emit_config(spec)


def test_emitted_text_is_lf_tab_indented_and_ends_with_newline(hill_text: str) -> None:
    text = emit_config(spec_from_config(parse_config(hill_text)), source="x.yaml")
    assert "\r" not in text and text.endswith("]\n")
    assert "GENERATED by dms-arma" in text and "Spec: x.yaml" in text
    body = text[text.index("createHashMapFromArray") :]
    assert all(not ln.startswith(" ") for ln in body.splitlines())


def test_config_keys_match_emission_order(hill_text: str) -> None:
    spec = spec_from_config(parse_config(hill_text))
    assert tuple(k for s in config_sections(spec) for k, _, _ in s.entries) == CONFIG_KEYS
    assert tuple(config_values(spec)) == CONFIG_KEYS


def test_every_key_the_scripts_read_is_in_the_spec() -> None:
    import re

    used: set[str] = set()
    for path in HILL.rglob("*.sqf"):
        used |= set(re.findall(r'DMS_cfg\s+get\s+"(\w+)"|_cfg\s+get\s+"(\w+)"', path.read_text()))
    keys = {k for pair in used for k in pair if k}
    assert keys, "expected the mission scripts to read DMS_cfg keys"
    assert keys <= set(CONFIG_KEYS), (
        f"read by scripts but not in the spec: {keys - set(CONFIG_KEYS)}"
    )


def test_example_spec_validates_and_round_trips() -> None:
    spec = load_spec(EXAMPLE)
    assert spec.template == "the_hill" and spec.world == "Altis"
    assert spec_from_config(parse_config(emit_config(spec))) == spec
    assert ROOT.is_dir()
