    ap.add_argument("--ram-wait", type=float, default=600, help="max seconds to wait for RAM")
    ap.add_argument("--arma", type=Path, default=Path(os.environ.get("ARMA3_DIR", DEFAULT_ARMA)))
    ap.add_argument("--profile", type=Path, default=DEFAULT_PROFILE)
    ap.add_argument("--report", type=Path, default=None)
    ap.add_argument("--keep-mission", action="store_true", help="leave the MPMissions copy")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--quiet", action="store_true", help="do not echo [DMS] lines live")
    a = ap.parse_args(argv)
    a.parallel = max(1, min(a.parallel, MAX_PARALLEL))

    mission = a.mission.resolve()
    if not (mission / "mission.sqm").is_file():
        print(f"not a mission folder: {mission}", file=sys.stderr)
        return 2
    name, _, world = mission.name.rpartition(".")
    if not name or not world:
        print("mission folder must be named <name>.<world>", file=sys.stderr)
        return 2
    tname = name if name.lower().startswith("dms_") else f"dms_{name}"
    a.mod_paths = resolve_mods(a.mods) if a.mods else []
    exe = next((a.arma / e for e in SERVER_EXES if (a.arma / e).is_file()), None)
    if exe is None:
        print(f"arma3server_x64.exe not found in {a.arma}", file=sys.stderr)
        return 2

    base: dict[str, object] = {}
    if not a.diag:
        if not a.no_test_mode:
            base["DMS_testMode"] = 1
            base["DMS_testMinutes"] = max(1, int(a.minutes))
            base["DMS_testTimeScale"] = a.time_scale
            base["DMS_testStartDist"] = a.start_dist
            base["DMS_testAssist"] = a.assist
        base.setdefault("DMS_debug", 0)
    for kv in a.param:
        k, _, v = kv.partition("=")
        base[k.strip()] = v.strip()

    seeds: list[int | None] = (
        [int(x) for x in a.seeds.split(",") if x.strip()] if a.seeds else [a.seed]
    )
    multi = len(seeds) > 1
    stamp = time.strftime("%Y%m%d_%H%M%S")
    profile_root = a.profile.resolve()
    jobs: list[Job] = []
    for i, seed in enumerate(seeds):
        params = dict(base)
        if seed is not None and not a.diag:
            params["DMS_seed"] = seed
        tag = f"s{seed}" if seed is not None else "run"
        template = f"{tname}_{tag}.{world}" if multi else f"{tname}.{world}"
        profile = profile_root / tag if multi else profile_root
        if a.report and not multi:
            report = a.report
        else:
            report = profile_root / "reports" / f"{template}_{stamp}.json"
        jobs.append(Job(tag, template, params, profile, a.port + 20 * i, report))

    for j in jobs:
        print(f"[harness] {j.tag}: {j.template} profile={j.profile} params={j.params}")
    print(f"[harness] parallel={a.parallel} priority={a.priority} free RAM {free_ram_gb():.1f} GB")
    if a.dry_run:
        return 0
    if hits := running_servers():
        print("[harness] REFUSING: an Arma 3 server is already running:\n  " + "\n  ".join(hits))
        return 2

    t0 = time.time()
    results: list[tuple[Job, int, Report]] = []
    with ThreadPoolExecutor(max_workers=a.parallel) as ex:
        futs = {ex.submit(run_one, a, mission, exe, j): j for j in jobs}
        for fut in as_completed(futs):
            j = futs[fut]
            code, rep = fut.result()
            print_report(j.tag, rep, j.report)
            results.append((j, code, rep))
    total = time.time() - t0

    worst = max(code for _, code, _ in results)
    if multi:
        runs = [
            {
                "tag": j.tag,
                "code": c,
                "verdict": r.verdict,
                "wall": r.wall_seconds,
                "summary": r.summary,
                "outcome": r.outcomes[0].get("raw") if r.outcomes else "",
                "report": str(j.report),
            }
            for j, c, r in sorted(results, key=lambda x: x[0].tag)
        ]
        out = profile_root / "reports" / f"{tname}_batch_{stamp}.json"
        batch = {"wall_seconds": round(total, 1), "runs": runs}
        out.write_text(json.dumps(batch, indent=2), "utf-8")
        print(f"[harness] batch: {len(jobs)} runs in {total:.0f} s wall -> {out}")
        for r in runs:
            print(f"    {r['tag']:>6} code={r['code']} {r['wall']:.0f}s {r['verdict']}")
    return worst


