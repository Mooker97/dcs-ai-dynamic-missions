--# modules: core
describe("DMS.Log", function()
  before_each(function()
    DMS.Log._debug = nil
    DMS_CONFIG = nil
  end)

  it("formats with prefix via env.info/warning/error", function()
    DMS.Log.info("Test", "hello %s %d", "world", 3)
    DMS.Log.warn("Test", "careful")
    DMS.Log.error("Test", "boom %s", nil)
    assert.is_true((MOCK.logContains("^%[DMS%]%[Test%] hello world 3$", "info")))
    assert.is_true((MOCK.logContains("careful", "warning")))
    assert.is_true((MOCK.logContains("boom nil", "error")))
  end)

  it("never throws on bad format arguments", function()
    DMS.Log.info("T", "%d items", "notanumber")
    DMS.Log.info("T", "%s", { 1 })
    DMS.Log.info("T", nil)
    assert.is_true((MOCK.logContains("%%d items notanumber")))
  end)

  it("debug follows DMS_CONFIG.debug unless overridden", function()
    DMS.Log.debug("T", "hidden")
    assert.is_false((MOCK.logContains("hidden")))
    DMS_CONFIG = { debug = true }
    assert.is_true(DMS.Log.isDebug())
    DMS.Log.debug("T", "shown")
    assert.is_true((MOCK.logContains("shown")))
    DMS.Log.setDebug(false)
    assert.is_false(DMS.Log.isDebug())
  end)
end)

describe("DMS.safeCall", function()
  it("returns results on success", function()
    local ok, a, b = DMS.safeCall(function(x, y)
      return x + y, "z"
    end, 1, 2)
    assert.is_true(ok)
    assert.equals(3, a)
    assert.equals("z", b)
  end)

  it("passes nil arguments through", function()
    local ok, n = DMS.safeCall(function(...)
      return select("#", ...)
    end, nil, nil, 3)
    assert.is_true(ok)
    assert.equals(3, n)
  end)

  it("catches errors, logs with traceback under prefix safeCall", function()
    local ok, err = DMS.safeCall(function()
      error("kaboom")
    end)
    assert.is_false(ok)
    assert.matches("kaboom", err)
    assert.matches("stack traceback", err)
    assert.is_true((MOCK.logContains("%[DMS%]%[safeCall%].*kaboom", "error")))
  end)

  it("rejects non-callables without throwing", function()
    local ok = DMS.safeCall(nil)
    assert.is_false(ok)
  end)
end)

describe("DMS.Json / outcome", function()
  it("encodes scalars, arrays and sorted objects", function()
    assert.equals("null", DMS.Json.encode(nil))
    assert.equals('[1,2.5,"a"]', DMS.Json.encode({ 1, 2.5, "a" }))
    assert.equals('{"a":true,"b":{"c":[false]}}', DMS.Json.encode({ b = { c = { false } }, a = true }))
    assert.equals("{}", DMS.Json.encode({}))
  end)

  it("escapes strings and handles non-finite numbers and mixed keys", function()
    assert.equals('"q\\"b\\\\n\\nt\\u0001"', DMS.Json.encode('q"b\\n\nt\1'))
    assert.equals("null", DMS.Json.encode(math.huge))
    assert.equals('{"1":"x","k":2}', DMS.Json.encode({ [1] = "x", k = 2 }))
  end)

  it("errors on cycles; outcome logs instead of throwing", function()
    local t = {}
    t.self = t
    assert.has_error(function()
      DMS.Json.encode(t)
    end)
    assert.is_nil(DMS.Log.outcome(t))
    local line = DMS.Log.outcome({ hvtKilled = true, losses = 1 })
    assert.equals('[DMS.OUTCOME] {"hvtKilled":true,"losses":1}', line)
    assert.is_true((MOCK.logContains("DMS.OUTCOME", "info")))
  end)
end)
