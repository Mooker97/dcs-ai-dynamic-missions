--# modules: core, clock, rng, bus, registry
describe("DMS.Registry", function()
  before_each(function()
    DMS_CONFIG = { budgets = { maxActiveGround = 5, maxActiveAir = 2, spawnsPerMin = 2 } }
  end)

  it("allocName() is unique and skips existing names", function()
    MOCK.addGroup({ name = "DMS_sam_2", coalition = 1 })
    assert.equals("DMS_sam_1", DMS.Registry.allocName("sam"))
    assert.equals("DMS_sam_3", DMS.Registry.allocName("sam"))
    assert.equals("DMS_sam_4", DMS.Registry.allocName("sam"))
    assert.equals("DMS_qrf_1", DMS.Registry.allocName("qrf"))
  end)

  it("track() fills meta from the live group; get/untrack/list", function()
    MOCK.addGroup({ name = "A", coalition = 1, count = 3 })
    MOCK.addGroup({ name = "H", coalition = 2, category = "helicopter", count = 1 })
    local m = DMS.Registry.track("A", { encounter = "e1" })
    assert.equals("ground", m.category)
    assert.equals(1, m.coalition)
    assert.equals(3, m.units)
    DMS.Registry.track("H")
    assert.equals("air", DMS.Registry.get("H").category)
    assert.same({ "A", "H" }, DMS.Registry.list())
    assert.same({ "A" }, DMS.Registry.list(function(_, meta) return meta.encounter == "e1" end))
    DMS.Registry.untrack("A")
    assert.is_nil(DMS.Registry.get("A"))
  end)

  it("isAlive() and count() are late-activation aware", function()
    MOCK.addGroup({ name = "L", coalition = 1, count = 2, lateActivation = true })
    DMS.Registry.track("L")
    assert.is_false(DMS.Registry.isAlive("L"))
    assert.equals(0, DMS.Registry.count("ground", 1))
    Group.getByName("L"):activate()
    assert.is_true(DMS.Registry.isAlive("L"))
    assert.equals(2, DMS.Registry.count("ground", 1))
    MOCK.killGroup("L")
    assert.is_false(DMS.Registry.isAlive("L"))
    assert.is_false(DMS.Registry.isAlive("nope"))
    assert.is_true(DMS.Registry.get("L").dead)
  end)

  it("count() and budgetAvailable() per category/coalition", function()
    MOCK.addGroup({ name = "A", coalition = 1, count = 3 })
    MOCK.addGroup({ name = "B", coalition = 2, count = 4 })
    MOCK.addGroup({ name = "F", coalition = 1, category = "airplane", count = 2, alt = 3000 })
    MOCK.addGroup({ name = "Untracked", coalition = 1, count = 10 })
    DMS.Registry.track("A")
    DMS.Registry.track("B")
    DMS.Registry.track("F")
    assert.equals(3, DMS.Registry.count("ground", 1))
    assert.equals(7, DMS.Registry.count("ground"))
    assert.equals(9, DMS.Registry.count())
    assert.is_true(DMS.Registry.budgetAvailable("ground", 1, 2))
    assert.is_false(DMS.Registry.budgetAvailable("ground", 1, 3))
    assert.is_false(DMS.Registry.budgetAvailable("air", 1, 1))
    MOCK.killUnit("A-1")
    assert.is_true(DMS.Registry.budgetAvailable("ground", 1, 3))
    assert.is_true(DMS.Registry.budgetAvailable("ship", 1, 99))
    DMS_CONFIG = nil
    assert.is_true(DMS.Registry.budgetAvailable("ground", 1, 999))
  end)

  it("spawnRateAvailable() uses a 60 s window", function()
    MOCK.addGroup({ name = "A", coalition = 1 })
    MOCK.addGroup({ name = "B", coalition = 1 })
    assert.is_true(DMS.Registry.spawnRateAvailable())
    DMS.Registry.track("A")
    DMS.Registry.track("B")
    assert.is_false(DMS.Registry.spawnRateAvailable())
    MOCK.advance(61)
    assert.is_true(DMS.Registry.spawnRateAvailable())
  end)
end)
