TS_RE = re.compile(r"^\s*(\d{1,2}:\d{2}:\d{2})\s?(.*)$")
TEST_RE = re.compile(r"\[DMS\.TEST\]\s+(PASS|FAIL|DONE|SUMMARY)\b\s*(\S+)?\s*(.*)$")
OUTCOME_RE = re.compile(r"\[DMS\.OUTCOME\]\s*(.*)$")
DMS_RE = re.compile(r"\[DMS\]\s+(\w+):\s*(.*)$")
DIAG_RE = re.compile(r"\[DMS\.DIAG\]\s*(.*)$")
ERR_START_RE = re.compile(r"^Error in expression")
ERR_CONT_RE = re.compile(r"^(Error position|Error |File .*line \d+)")
INFRA_PATTERNS = (
    "Mission file(s) not found",
    "Cannot load mission",
    "No entry 'bin\\config.bin",
    "Server error: Player without identity",
    "Failed to initialize Steam",
    "Steam initialization failed",
    "Cannot open file",
)


@dataclass
class Report:
    mission: str = ""
    template: str = ""
    params: dict[str, object] = field(default_factory=dict)
    rpt: str = ""
    started: bool = False
    done: bool = False
    exit_reason: str = ""
    wall_seconds: float = 0.0
    tests: list[dict[str, str]] = field(default_factory=list)
    summary: str = ""
    outcomes: list[dict[str, str]] = field(default_factory=list)
    script_errors: list[str] = field(default_factory=list)
    dms_warnings: list[str] = field(default_factory=list)
    dms_lines: list[str] = field(default_factory=list)
    diag: list[str] = field(default_factory=list)
    infra: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    verdict: str = ""


def _kv(s: str) -> dict[str, str]:
    return dict(re.findall(r"(\w+)=(\S+)", s))


def parse_rpt(text: str, rep: Report) -> None:
    lines = text.splitlines()
    err: list[str] | None = None

    def flush() -> None:
        nonlocal err
        if err:
            block = "\n".join(err)
            if block not in rep.script_errors:
                rep.script_errors.append(block)
        err = None

    for raw in lines:
        m = TS_RE.match(raw)
        body = (m[2] if m else raw).strip()
        if ERR_START_RE.match(body):
            flush()
            err = [body[:1500]]
            continue
        if err is not None and ERR_CONT_RE.match(body):
            err.append(body[:1500])
            continue
        if body.startswith("Error ") and err is None:  # stray error without the header line
            err = [body[:1500]]
            continue
        flush()
        if t := TEST_RE.search(body):
            status = t[1]
            if status == "DONE":
                rep.done = True
            elif status == "SUMMARY":
                rep.summary = ((t[2] or "") + " " + t[3]).strip()
            else:
                rep.tests.append({"status": status, "name": t[2] or "", "detail": t[3].strip()})
            continue
        if o := OUTCOME_RE.search(body):
            d = _kv(o[1])
            d["raw"] = o[1]
            rep.outcomes.append(d)
            continue
        if d := DIAG_RE.search(body):
            rep.diag.append(d[1])
            continue
        if dm := DMS_RE.search(body):
            rep.dms_lines.append(body[:500])
            if dm[1] in ("WARN", "ERROR"):
                rep.dms_warnings.append(body[:500])
            if "initServer done" in body:
                rep.started = True
            continue
        if "[DMS.DIAG.BEGIN]" in body:
            rep.started = True
        for pat in INFRA_PATTERNS:
            if pat in body:
                rep.infra.append(body[:400])
    flush()


def verdict(rep: Report, diag: bool) -> int:
    if not rep.started:
        rep.verdict = "INFRA: mission never started"
        return 2
    if diag:
        rep.verdict = "DIAG done" if rep.done else "DIAG incomplete"
        return 0 if rep.done and not rep.script_errors else 1
    fails = [t for t in rep.tests if t["status"] == "FAIL"]
    if rep.script_errors or fails or not rep.summary:
        why = []
        if rep.script_errors:
            why.append(f"{len(rep.script_errors)} script error(s)")
        if fails:
            why.append("FAIL: " + ", ".join(t["name"] for t in fails))
        if not rep.summary:
            why.append("no summary (" + (rep.exit_reason or "?") + ")")
        rep.verdict = "FAIL: " + "; ".join(why)
        return 1
    rep.verdict = "PASS"
    return 0


