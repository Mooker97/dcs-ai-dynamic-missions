def running_servers() -> list[str]:
    out = subprocess.run(
        ["tasklist", "/FO", "CSV", "/NH"], capture_output=True, text=True, errors="replace"
    ).stdout
    hits = []
    for line in out.splitlines():
        name = line.split(",")[0].strip('"').lower()
        if name in SERVER_EXES:
            hits.append(line.strip())
    return hits


def kill_tree(proc: subprocess.Popen[bytes]) -> None:
    if proc.poll() is not None:
        return
    subprocess.run(["taskkill", "/PID", str(proc.pid), "/T", "/F"], capture_output=True, text=True)
    with contextlib.suppress(Exception):
        proc.wait(timeout=20)


def free_port(start: int) -> int:
    """Arma uses port..port+3 (UDP). Return the first base port whose 4 ports bind."""
    for base in range(start, start + 200, 10):
        ok = True
        for p in range(base, base + 4):
            s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
            try:
                s.bind(("0.0.0.0", p))
            except OSError:
                ok = False
            finally:
                s.close()
        if ok:
            return base
    raise RuntimeError("no free UDP port range found")


