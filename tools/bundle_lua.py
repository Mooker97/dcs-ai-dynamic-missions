"""Bundle the DMS Lua runtime into a single DO SCRIPT FILE.

Concatenates the modules listed in ``lua/manifest.txt`` (from ``lua/src/dms/``) into
``dist/dms.lua`` with ``-- ==== <file> ====`` headers and a version banner
(``<root pyproject version>+<git short sha>``), then verifies the result compiles under
Lua 5.1 via lupa. Missing modules are skipped with a warning.

Stdlib-only apart from that lupa check: ``--no-check`` skips it (CI's Lua job runs without the
project's dev deps and syntax-checks the result with ``luac -p`` instead).

Usage: ``uv run python tools/bundle_lua.py [--out dist/dms.lua] [--no-check]``
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
LUA_DIR = REPO_ROOT / "lua"
SRC_DIR = LUA_DIR / "src" / "dms"
MANIFEST = LUA_DIR / "manifest.txt"
DEFAULT_OUT = REPO_ROOT / "dist" / "dms.lua"


def read_manifest(path: Path = MANIFEST) -> list[str]:
    names: list[str] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            names.append(line)
    return names


def project_version() -> str:
    data = tomllib.loads((REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    return str(data.get("project", {}).get("version", "0.0.0"))


def git_sha() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            check=True,
        )
        return out.stdout.strip() or "nogit"
    except (OSError, subprocess.CalledProcessError):
        return "nogit"


def check_lua51(source: str, chunkname: str = "=dms.lua") -> str | None:
    """Return None if ``source`` compiles under Lua 5.1, else the error message."""
    from lupa import lua51

    lua = lua51.LuaRuntime(unpack_returned_tuples=True)
    res = lua.eval("loadstring")(source, chunkname)
    if isinstance(res, tuple) and res[0] is None:
        return str(res[1])
    return None


def build_source(quiet: bool = False) -> tuple[str, list[str], list[str]]:
    version = f"{project_version()}+{git_sha()}"
    included: list[str] = []
    missing: list[str] = []
    parts = [
        f"-- DMS runtime bundle {version}. Generated by tools/bundle_lua.py; do not edit.",
        f'DMS = DMS or {{}}; DMS.VERSION = "{version}"',
        "",
    ]
    for name in read_manifest():
        path = SRC_DIR / f"{name}.lua"
        if not path.is_file():
            missing.append(name)
            if not quiet:
                print(f"warning: module '{name}' not found ({path}), skipped", file=sys.stderr)
            continue
        included.append(name)
        body = path.read_text(encoding="utf-8").rstrip() + "\n"
        # each module is its own chunk scope so top-level locals don't collide / hit 200-local limit
        parts.append(f"-- ==== {name}.lua ====\ndo\n{body}end\n")
    return "\n".join(parts), included, missing


def bundle(out: Path | None = None, quiet: bool = False, check: bool = True) -> Path:
    out = out or DEFAULT_OUT
    source, included, _missing = build_source(quiet=quiet)
    if check:
        err = check_lua51(source, "@" + out.name)
        if err:
            raise SystemExit(f"bundle failed Lua 5.1 syntax check: {err}")
    elif not quiet:
        print("note: Lua 5.1 syntax check skipped (--no-check); run luac -p", file=sys.stderr)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(source, encoding="utf-8", newline="\n")
    if not quiet:
        print(f"wrote {out} ({len(included)} modules: {', '.join(included)})")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--out", type=Path, default=DEFAULT_OUT, help="output file (default dist/dms.lua)"
    )
    ap.add_argument("-q", "--quiet", action="store_true")
    ap.add_argument(
        "--no-check",
        action="store_true",
        help="skip the lupa Lua 5.1 syntax check (no third-party imports; use luac -p after)",
    )
    args = ap.parse_args(argv)
    bundle(args.out, quiet=args.quiet, check=not args.no_check)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
