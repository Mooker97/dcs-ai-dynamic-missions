from __future__ import annotations

import shutil
from pathlib import Path

import pytest
from arma_paths import EXAMPLE, HILL
from dms_arma import build_mission, config_diff, config_values, load_spec, parse_config
from dms_arma.cli import main
from dms_arma.mission import CONFIG_PATH, dump_spec


@pytest.fixture
def template(tmp_path: Path) -> Path:
    if not HILL.is_dir():
        pytest.skip("The Hill mission not present")
    # Work on a copy so nothing can ever touch the live mission.
    dst = tmp_path / "template" / HILL.name
    shutil.copytree(HILL, dst)
    return dst


def test_build_writes_generated_config(template: Path, tmp_path: Path) -> None:
    spec = load_spec(EXAMPLE)
    out = tmp_path / "out" / "dms_gen.Altis"
    issues = build_mission(spec, template, out, source="the_hill.yaml")
    assert issues == []
    text = (out / CONFIG_PATH).read_text(encoding="utf-8")
    assert "GENERATED by dms-arma" in text
    assert config_diff(parse_config(text), config_values(spec)) == []
    assert (out / "description.ext").is_file() and (out / "mission.sqm").is_file()
    with pytest.raises(FileExistsError):
        build_mission(spec, template, out)
    assert build_mission(spec, template, out, overwrite=True) == []


def test_build_refuses_to_write_into_template(template: Path) -> None:
    with pytest.raises(ValueError):
        build_mission(load_spec(EXAMPLE), template, template)
    with pytest.raises(ValueError):
        build_mission(load_spec(EXAMPLE), template, template / "sub")


def test_site_count_must_match_description_params(template: Path, tmp_path: Path) -> None:
    spec = load_spec(EXAMPLE)
    spec.sites.sites = spec.sites.sites[:2]
    issues = build_mission(spec, template, tmp_path / "o.Altis")
    assert [i.where for i in issues] == ["description.ext Params/DMS_site"]


def test_yaml_dump_round_trips() -> None:
    spec = load_spec(EXAMPLE)
    p = Path(EXAMPLE)
    assert dump_spec(spec) == p.read_text(encoding="utf-8")


def test_cli(template: Path, tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    cfg = tmp_path / "fn_config.sqf"
    assert main(["emit", str(EXAMPLE), "-o", str(cfg)]) == 0
    yml = tmp_path / "spec.yaml"
    assert main(["import", str(cfg), "-o", str(yml)]) == 0
    assert load_spec(yml) == load_spec(EXAMPLE)
    assert main(["validate", str(EXAMPLE), "--strict"]) == 0
    out = tmp_path / "built.Altis"
    assert main(["build", str(EXAMPLE), "--template", str(template), "--out", str(out)]) == 0
    assert (out / CONFIG_PATH).is_file()
