--# modules: core, clock, rng, bus, registry
local function collect(name)
  local got = {}
  DMS.Bus.on(name, function(p)
    got[#got + 1] = p
  end)
  return got
end

describe("DMS.Bus pub/sub", function()
  it("on/emit/off with tokens", function()
    local got = {}
    local tok = DMS.Bus.on("x.y", function(p, n)
      got[#got + 1] = n .. ":" .. p.v
    end)
    DMS.Bus.emit("x.y", { v = 1 })
    assert.is_true(DMS.Bus.off(tok))
    DMS.Bus.emit("x.y", { v = 2 })
    assert.same({ "x.y:1" }, got)
    assert.is_false(DMS.Bus.off(tok))
  end)

  it("isolates handler errors and supports '*'", function()
    local all = {}
    DMS.Bus.on("e", function()
      error("handler broke")
    end)
    local after = collect("e")
    DMS.Bus.on("*", function(_, n)
      all[#all + 1] = n
    end)
    DMS.Bus.emit("e", {})
    assert.equals(1, #after)
    assert.same({ "e" }, all)
    assert.is_true((MOCK.logContains("handler broke", "error")))
  end)

  it("handlers may unsubscribe during emit", function()
    local n = 0
    local tok
    tok = DMS.Bus.on("e", function()
      n = n + 1
      DMS.Bus.off(tok)
    end)
    DMS.Bus.emit("e", {})
    DMS.Bus.emit("e", {})
    assert.equals(1, n)
  end)
end)

describe("DMS.Bus DCS events", function()
  it("player.spawned from BIRTH with player name; player.left on leave", function()
    local sp, left = collect("player.spawned"), collect("player.left")
    local u = MOCK.spawnPlayer({ name = "Viper1-1", group = "Viper1", playerName = "Mav", type = "F-16C_50" })
    assert.equals(1, #sp)
    assert.equals("Viper1-1", sp[1].unit)
    assert.equals("Viper1", sp[1].group)
    assert.equals("Mav", sp[1].playerName)
    assert.equals(2, sp[1].coalition)
    assert.equals("F-16C_50", sp[1].typeName)
    assert.is_number(sp[1].groupId)
    MOCK.fireEvent({ id = "PLAYER_LEAVE_UNIT", initiator = u })
    MOCK.fireEvent({ id = "PLAYER_LEAVE_UNIT", initiator = u })
    assert.equals(1, #left)
    assert.equals("Mav", left[1].playerName)
  end)

  it("AI births do not emit player.spawned", function()
    local sp = collect("player.spawned")
    MOCK.addGroup({ name = "R", coalition = 1, count = 2 })
    assert.equals(0, #sp)
  end)

  it("unit.dead is de-duplicated across KILL/DEAD/UNIT_LOST/CRASH and carries cached info", function()
    local dead = collect("unit.dead")
    MOCK.addGroup({ name = "T", coalition = 1, units = { { name = "T-1", type = "T-72B", x = 10, y = 20 } } })
    MOCK.spawnPlayer({ name = "P-1" })
    local obj = Unit.getByName("T-1")
    MOCK.killUnit("T-1", { killer = "P-1", weapon = "AGM_65D" })
    MOCK.fireEvent({ id = "CRASH", initiator = obj })
    assert.equals(1, #dead)
    local d = dead[1]
    assert.equals("T-1", d.unit)
    assert.equals("T", d.group)
    assert.equals(1, d.coalition)
    assert.equals("ground", d.category)
    assert.equals("T-72B", d.typeName)
    assert.equals(10, d.pos.x)
    assert.equals(20, d.pos.z)
    assert.equals("P-1", d.killer)
  end)

  it("a duplicate within 5 s is dropped; after 5 s it is a new death", function()
    local dead = collect("unit.dead")
    MOCK.addGroup({ name = "T", coalition = 1, units = { { name = "T-1" }, { name = "T-2" } } })
    local obj = Unit.getByName("T-1")
    MOCK.killUnit("T-1", { events = { "UNIT_LOST" } })
    MOCK.advance(4)
    MOCK.fireEvent({ id = "DEAD", initiator = obj })
    assert.equals(1, #dead)
    MOCK.advance(2)
    MOCK.fireEvent({ id = "DEAD", initiator = obj })
    assert.equals(2, #dead)
  end)

  it("group.dead fires once when the last unit dies, even if only UNIT_LOST arrives", function()
    local gd = collect("group.dead")
    MOCK.addGroup({ name = "G", coalition = 1, count = 3 })
    MOCK.killUnit("G-1")
    MOCK.killUnit("G-2", { events = { "UNIT_LOST" } })
    assert.equals(0, #gd)
    MOCK.killUnit("G-3", { events = { "DEAD" } })
    assert.equals(1, #gd)
    assert.equals("G", gd[1].group)
    assert.equals(1, gd[1].coalition)
  end)

  it("knows silently placed groups via Registry.track", function()
    local gd = collect("group.dead")
    MOCK.addGroup({ name = "Pre", coalition = 2, count = 2, silent = true })
    DMS.Registry.track("Pre", { encounter = "x" })
    MOCK.killGroup("Pre", { events = { "UNIT_LOST" } })
    assert.equals(1, #gd)
    assert.equals(2, gd[1].coalition)
  end)

  it("ignores nil, weapon and scenery initiators safely", function()
    local dead, hit = collect("unit.dead"), collect("unit.hit")
    MOCK.fireEvent({ id = "DEAD" })
    MOCK.fireEvent({ id = "DEAD", initiator = MOCK.makeScenery("house") })
    MOCK.fireEvent({ id = "DEAD", initiator = MOCK.makeWeapon("Mk_82") })
    MOCK.fireEvent({ id = "KILL" })
    MOCK.fireEvent({ id = "HIT", initiator = MOCK.makeWeapon("x"), target = MOCK.makeScenery("y") })
    MOCK.fireEvent({ id = "HIT", target = {} })
    assert.equals(0, #dead)
    assert.equals(0, #hit)
  end)

  it("statics die as category 'static'", function()
    local dead = collect("unit.dead")
    local s = coalition.addStaticObject(country.id.RUSSIA, { name = "Depot", type = "Warehouse", x = 1, y = 2 })
    MOCK.fireEvent({ id = "DEAD", initiator = s })
    assert.equals(1, #dead)
    assert.equals("static", dead[1].category)
    assert.equals("Depot", dead[1].unit)
  end)

  it("unit.hit / unit.shot payloads; initiator may be nil", function()
    local hit, shot = collect("unit.hit"), collect("unit.shot")
    MOCK.addGroup({ name = "T", coalition = 1, units = { { name = "T-1" } } })
    local p = MOCK.spawnPlayer({ name = "P-1", group = "P" })
    MOCK.hitUnit("T-1", { initiator = "P-1", weapon = "GBU_12" })
    MOCK.hitUnit("T-1", {})
    MOCK.fireEvent({ id = "SHOT", initiator = p, weapon = MOCK.makeWeapon("AIM_9X") })
    assert.equals(2, #hit)
    assert.equals("T-1", hit[1].target)
    assert.equals("T", hit[1].targetGroup)
    assert.equals(1, hit[1].targetCoalition)
    assert.equals("P-1", hit[1].initiator)
    assert.equals("P", hit[1].initiatorGroup)
    assert.equals("GBU_12", hit[1].weapon)
    assert.is_nil(hit[2].initiator)
    assert.equals(1, #shot)
    assert.equals("P-1", shot[1].initiator)
    assert.equals(2, shot[1].coalition)
    assert.equals("AIM_9X", shot[1].weapon)
  end)

  it("takeoff/landed and marks", function()
    local to, la, ma = collect("unit.takeoff"), collect("unit.landed"), collect("mark.added")
    local p = MOCK.spawnPlayer({ name = "P-1", group = "P" })
    MOCK.fireEvent({ id = "TAKEOFF", initiator = p, place = MOCK.makeAirbase("Batumi") })
    MOCK.fireEvent({ id = "LAND", initiator = p })
    MOCK.fireEvent({
      id = "MARK_ADDED",
      idx = 7,
      text = "tgt",
      pos = { x = 1, y = 0, z = 2 },
      coalition = 2,
      groupID = 5,
    })
    assert.equals("Batumi", to[1].place)
    assert.equals("P", to[1].group)
    assert.equals("P-1", la[1].unit)
    assert.equals(7, ma[1].idx)
    assert.equals("tgt", ma[1].text)
    assert.equals(5, ma[1].groupId)
  end)

  it("a player dying emits player.left once", function()
    local left = collect("player.left")
    MOCK.spawnPlayer({ name = "P-1", playerName = "Mav" })
    MOCK.killUnit("P-1", { crash = true })
    assert.equals(1, #left)
  end)

  it("respawned group with the same name can die again", function()
    local gd = collect("group.dead")
    MOCK.addGroup({ name = "R", coalition = 1, count = 1 })
    MOCK.killGroup("R")
    MOCK.advance(10)
    MOCK.addGroup({ name = "R", coalition = 1, count = 1 })
    MOCK.killGroup("R")
    assert.equals(2, #gd)
  end)
end)
