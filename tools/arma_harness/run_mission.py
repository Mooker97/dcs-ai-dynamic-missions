def resolve_mods(spec: str, workshop: Path = WORKSHOP) -> list[Path]:
    """'core' | 'core,1808238502' | ids | folder paths -> existing mod folders.

    Raises SystemExit if a mod folder has no addons/ directory.
    """
    out: list[Path] = []
    for item in [x.strip() for x in spec.split(",") if x.strip()]:
        for one in MOD_PRESETS.get(item, [item]):
            path = Path(one) if (":" in one or "/" in one or "\\" in one) else workshop / one
            if not (path / "addons").is_dir():
                raise SystemExit(f"mod not found (no addons folder): {path}")
            if path not in out:
                out.append(path)
    return out


def wait_for_ram(a: argparse.Namespace, tag: str) -> bool:
    """Block until --min-free-gb is available (or give up after --ram-wait seconds)."""
    t0 = time.time()
    warned = False
    while True:
        gb = free_ram_gb()
        if gb >= a.min_free_gb:
            return True
        if time.time() - t0 > a.ram_wait:
            say(f"[{tag}] only {gb:.1f} GB free after waiting {a.ram_wait:.0f} s; not launching")
            return False
        if not warned:
            say(f"[{tag}] waiting for {a.min_free_gb} GB free RAM (now {gb:.1f} GB)")
            warned = True
        time.sleep(10)


def run_one(a: argparse.Namespace, mission: Path, exe: Path, job: Job) -> tuple[int, Report]:
    rep = Report(mission=str(mission), template=job.template, params=job.params)
    tag = job.tag
    job.profile.mkdir(parents=True, exist_ok=True)
    cfg = server_cfg(job.template, job.params, a.difficulty)
    (job.profile / "server.cfg").write_text(cfg, "utf-8")
    (job.profile / "basic.cfg").write_text(BASIC_CFG, "utf-8")
    dest = a.arma / "MPMissions" / job.template
    wall = a.wall_timeout or (a.minutes * 60 + 240)

    with _launch_lock:  # one launch at a time, so the RAM check sees the previous server loaded
        if not wait_for_ram(a, tag):
            rep.verdict = "INFRA: not enough free RAM"
            rep.exit_reason = "ram"
            return 2, rep
        port = free_port(job.port)
        cmd = [
            str(exe),
            f"-config={job.profile / 'server.cfg'}",
            f"-cfg={job.profile / 'basic.cfg'}",
            f"-profiles={job.profile}",
            "-name=dms",
            "-autoInit",
            f"-port={port}",
            "-noSound",
            "-world=empty",
        ]
        if a.mod_paths:
            cmd.append("-mod=" + ";".join(str(m) for m in a.mod_paths))
        if dest.exists():
            shutil.rmtree(dest)
        shutil.copytree(mission, dest)
        t0 = time.time()
        proc = subprocess.Popen(
            cmd,
            cwd=str(a.arma),
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            creationflags=PRIORITY[a.priority],
        )
        say(f"[{tag}] pid {proc.pid} port {port} {job.template} params={job.params}")
        if a.parallel > 1:
            time.sleep(20)  # let it load Altis before the next RAM check

    rpt: Path | None = None
    pos = 0
    buf = ""
    stop_at: float | None = None
    try:
        while True:
            time.sleep(1)
            el = time.time() - t0
            if proc.poll() is not None:
                rep.exit_reason = rep.exit_reason or f"server exited code {proc.returncode}"
                break
            if el > wall:
                rep.exit_reason = "wall timeout"
                break
            if rpt is None:
                rpt = newest_rpt(job.profile, t0)
                if rpt is None:
                    if el > 120:
                        rep.exit_reason = "no .rpt after 120 s"
                        break
                    continue
            with rpt.open("r", encoding="utf-8", errors="replace") as fh:
                fh.seek(pos)
                chunk = fh.read()
                pos = fh.tell()
            buf += chunk
            *full, buf = buf.split("\n")
            for line in full:
                body = line.strip()
                is_err = "Error in expression" in body
                if not a.quiet and ("[DMS" in body or is_err):
                    say(f"[{tag}] {el:5.0f}s | {body[:220]}")
                if stop_at is None:
                    if "[DMS.TEST] DONE" in body:
                        rep.exit_reason, stop_at = "done", time.time() + 1
                    elif "[DMS.OUTCOME]" in body:
                        rep.exit_reason, stop_at = "outcome", time.time() + 3  # summary follows
                    elif not a.no_fail_fast and not a.diag and (is_err or FAIL_RE.search(body)):
                        rep.exit_reason = "fail-fast: " + ("script error" if is_err else "FAIL")
                        stop_at = time.time() + 2  # let the error block finish
                if "initServer done" in body or "[DMS.DIAG.BEGIN]" in body:
                    rep.started = True
            if stop_at and time.time() > stop_at:
                break
            if not rep.started and el > 300:
                rep.exit_reason = "mission did not start within 300 s"
                break
    finally:
        kill_tree(proc)
        rep.wall_seconds = round(time.time() - t0, 1)
        if not a.keep_mission and dest.exists() and dest.name.lower().startswith("dms_"):
            with contextlib.suppress(Exception):
                shutil.rmtree(dest)

    if rpt is None:
        rpt = newest_rpt(job.profile, t0)
    if rpt is not None:
        rep.rpt = str(rpt)
        parse_rpt(rpt.read_text(encoding="utf-8", errors="replace"), rep)
    else:
        rep.notes.append("no .rpt file written")
    code = verdict(rep, a.diag)
    job.report.parent.mkdir(parents=True, exist_ok=True)
    job.report.write_text(json.dumps(asdict(rep), indent=2), "utf-8")
    return code, rep


def print_report(tag: str, rep: Report, path: Path) -> None:
    lines = [f"[{tag}] {rep.verdict}  ({rep.wall_seconds:.0f} s wall, exit={rep.exit_reason})"]
    lines += [f"    {t['status']:4} {t['name']} {t['detail']}" for t in rep.tests]
    if rep.summary:
        lines.append(f"    SUMMARY {rep.summary}")
    lines += [f"    OUTCOME {o.get('raw', '')}" for o in rep.outcomes]
    for e in rep.script_errors[:10]:
        lines.append("    SCRIPT ERROR: " + e.replace("\n", "\n        "))
    lines += [f"    INFRA: {x}" for x in rep.infra[:5]]
    lines.append(f"    report: {path}")
    say("\n".join(lines))


